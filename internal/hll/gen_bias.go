//go:build ignore

// gen_bias measures the bias of the raw HyperLogLog estimate by simulation and writes bias_tables.go.
// For each precision it feeds many independent streams of random hashes into plain registers and
// records, at up to 200 cardinalities from 0 to 6·2^p, the mean raw estimate and its mean distance to the truth.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"math"
	"math/bits"
	"os"
)

const (
	minP   = 4
	maxP   = 14
	points = 200
)

func splitmix64(x *uint64) uint64 {
	*x += 0x9e3779b97f4a7c15
	z := *x
	z = (z ^ z>>30) * 0xbf58476d1ce4e5b9
	z = (z ^ z>>27) * 0x94d049bb133111eb
	return z ^ z>>31
}

func alpha(m int) float64 {
	switch m {
	case 16:
		return 0.673
	case 32:
		return 0.697
	case 64:
		return 0.709
	}
	return 0.7213 / (1 + 1.079/float64(m))
}

// measure returns the mean raw estimate and mean bias at each grid cardinality for precision p.
func measure(p int) (raw, bias []float64) {
	m := 1 << p
	grid := make([]int, min(points, 6*m+1))
	for i := range grid {
		grid[i] = i * 6 * m / (len(grid) - 1)
	}
	runs := max(400, (1<<23)/m)
	sums := make([]float64, len(grid))
	regs := make([]uint8, m)
	for run := range runs {
		clear(regs)
		harmonic := float64(m)
		seed := uint64(p)<<32 | uint64(run)
		n := 0
		for g, target := range grid {
			for ; n < target; n++ {
				h := splitmix64(&seed)
				idx := h >> (64 - p)
				rho := uint8(bits.LeadingZeros64(h<<p|1<<(p-1)) + 1)
				if rho > regs[idx] {
					harmonic += math.Ldexp(1, -int(rho)) - math.Ldexp(1, -int(regs[idx]))
					regs[idx] = rho
				}
			}
			sums[g] += alpha(m) * float64(m) * float64(m) / harmonic
		}
	}
	raw = make([]float64, len(grid))
	bias = make([]float64, len(grid))
	for g, target := range grid {
		raw[g] = sums[g] / float64(runs)
		bias[g] = raw[g] - float64(target)
	}
	return raw, bias
}

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_bias.go; DO NOT EDIT.\n\npackage hll\n\nvar biasTables = [...]biasTable{\n")
	for p := minP; p <= maxP; p++ {
		raw, bias := measure(p)
		b.WriteString("{\nraw: []float64{")
		for _, v := range raw {
			fmt.Fprintf(&b, "%.6g, ", v)
		}
		b.WriteString("},\nbias: []float64{")
		for _, v := range bias {
			fmt.Fprintf(&b, "%.6g, ", v)
		}
		b.WriteString("},\n},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile("bias_tables.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
